    async def asyncSetUp(self):
        self.state_dir = tempfile.TemporaryDirectory(prefix="pinngoo-browser-test-")
        env = {**os.environ, "PINNGOO_AI_TEST_MODE": "1", "PORT": "0", "PINNGOO_TEST_STATE_DIR": self.state_dir.name}
        self.server = await asyncio.create_subprocess_exec(
            "node",
            str(ROOT / "server.mjs"),
            cwd=ROOT,
            env=env,
            stdout=asyncio.subprocess.PIPE,
            stderr=asyncio.subprocess.PIPE,
        )
        ready_line = await asyncio.wait_for(self.server.stdout.readline(), timeout=10)
        match = re.search(rb"http://127\.0\.0\.1:(\d+)", ready_line)
        if not match:
            error = await self.server.stderr.read()
            self.fail(f"local API server did not start: {ready_line!r} {error.decode()}")
        page_url = f"http://127.0.0.1:{match.group(1).decode()}/"
        self.playwright = await async_playwright().start()
        self.browser = await self.playwright.chromium.launch(headless=True)
        self.context = await self.browser.new_context(viewport={"width": 1440, "height": 1000})
        self.page = await self.context.new_page()
        self.page_errors = []
        self.page.on("pageerror", lambda error: self.page_errors.append(str(error)))
        self.page.on(
            "console",
            lambda message: self.page_errors.append(message.text)
            if message.type == "error"
            else None,
        )
        await self.page.goto(page_url)
        await expect(self.page.locator("#view-home")).to_be_visible()

    async def asyncTearDown(self):
        await self.context.close()
        await self.browser.close()
        await self.playwright.stop()
        self.server.terminate()
        await asyncio.wait_for(self.server.wait(), timeout=5)
        self.state_dir.cleanup()

